import csv
import json
import os
import re
import uuid

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
NET = os.path.join(ROOT, "netlist9", "QS30-9_REV.A_netlist.csv")
OUT = os.path.join(ROOT, "kicad")
os.makedirs(OUT, exist_ok=True)

UU = lambda: str(uuid.uuid4())


def load():
    rows = []
    with open(NET, encoding="utf-8-sig") as f:
        for r in csv.DictReader(f):
            rows.append(r)
    return rows


def parts_of(rows, sheets):
    """按 sheet 前缀筛出该板器件及 pin→net。"""
    parts = {}
    for r in rows:
        if not any(r["sheet"].startswith(s) for s in sheets):
            continue
        p = parts.setdefault(r["ref"], dict(ref=r["ref"], mpn=r["mpn"], value=r["value"],
                                            package=r["package"], sheet=r["sheet"], pins={}))
        p["pins"][r["pin"]] = r["net"]
    return parts


def pin_layout(n):
    """返回 [(pin_index, x_local, y_local, angle)]，左右交替。"""
    out = []
    left = (n + 1) // 2
    for i in range(n):
        if i < left:
            out.append((i, -7.62, 2.54 * (left - 1) / 2 - 2.54 * i, 0))
        else:
            out.append((i, 7.62, 2.54 * (left - 1) / 2 - 2.54 * (i - left), 180))
    return out


def esc(s):
    return s.replace("\\", "\\\\").replace('"', '\\"')


def gen_symbol(lib_id, pins):
    """通用符号：n 引脚矩形；pins = [(number, name, x, y, angle)]"""
    xmax = max(abs(p[2]) for p in pins) + 5.08
    ymax = max(abs(p[3]) for p in pins) + 2.54
    out = [f'    (symbol "{lib_id}" (pin_names (offset 1.016)) (in_bom yes) (on_board yes)',
           f'      (property "Reference" "U" (at 0 {ymax:.2f} 0) (effects (font (size 1.27 1.27))))',
           f'      (property "Value" "GEN" (at 0 {-ymax:.2f} 0) (effects (font (size 1.27 1.27))))',
           f'      (symbol "{lib_id}_0_1"',
           f'        (rectangle (start {-xmax:.2f} {-ymax:.2f}) (end {xmax:.2f} {ymax:.2f})',
           '          (stroke (width 0) (type default)) (fill (type none)))',
           '      )',
           f'      (symbol "{lib_id}_1_1"']
    for number, name, x, y, angle in pins:
        out.append(f'        (pin passive line (at {x:.2f} {y:.2f} {angle}) (length 2.54)')
        out.append(f'          (name "{esc(name)}" (effects (font (size 1.27 1.27)))))')
        out.append(f'          (number "{esc(number)}" (effects (font (size 1.27 1.27)))))')
    out.append('      )')
    out.append('    )')
    return "\n".join(out)


def gen_sch(board_name, parts, paper="A3", title=""):
    refs = sorted(parts)
    # 分配 lib_symbols：按“引脚编号签名”分组（不同器件引脚号不同，不能共用一个符号）
    def sorter(s):
        return (len(s), s)
    sigs = {}
    for ref in refs:
        sig = tuple(sorted(parts[ref]["pins"].keys(), key=sorter))
        sigs.setdefault(sig, []).append(ref)
    libs = {}
    for sig, group in sigs.items():
        n = len(sig)
        lid = f"QS30:GEN{n}_{abs(hash(sig)) % 10000:04d}"
        lay = pin_layout(n)
        plist, indexes = [], {}
        for idx, num in enumerate(sig):
            x, y, ang = lay[idx][1], lay[idx][2], lay[idx][3]
            indexes[num] = (x, y)
            plist.append((num, num, x, y, ang))
        libs[sig] = (lid, gen_symbol(lid, plist), indexes)
    out = ['(kicad_sch (version 20230121) (generator eeschema)',
           f'  (uuid {UU()})',
           f'  (paper "{paper}")',
           f'  (title_block (title "{esc(title)}") (rev "REV.A9") (comment 1 "REV.A9 generated by design9/kicad_gen.py; not opened/ER-compiled; PROVISIONAL"))',
           '  (lib_symbols']
    for n in sorted(libs):
        out.append(libs[n][1])
    out.append('  )')
    # 放置符号 + 标签
    label_count = 0
    for i, ref in enumerate(refs):
        p = parts[ref]
        sig = tuple(sorted(p["pins"].keys(), key=lambda x: (len(x), x)))
        lid, _, indexes = libs[sig]
        X = 30.0 + (i % 6) * 24.0
        Y = 30.0 + (i // 6) * 26.0
        out.append(f'  (symbol (lib_id "{lid}") (at {X:.2f} {Y:.2f} 0) (unit 1)')
        out.append('    (in_bom yes) (on_board yes) (dnp no)')
        out.append(f'    (uuid {UU()})')
        out.append(f'    (property "Reference" "{ref}" (at {X+2.54:.2f} {Y-2.54:.2f} 0) (effects (font (size 1.27 1.27))))')
        out.append(f'    (property "Value" "{esc(p["value"][:28])}" (at {X+2.54:.2f} {Y-5.08:.2f} 0) (effects (font (size 1.27 1.27))))')
        out.append(f'    (property "Footprint" "{esc(p["package"])}" (at {X:.2f} {Y+5.08:.2f} 0) (effects (font (size 1.27 1.27)) hide))')
        nums = sorted(p["pins"], key=lambda s: (len(s), s))
        for num in nums:
            out.append(f'    (pin "{esc(num)}" (uuid {UU()}))')
        out.append(f'    (instances (project "{board_name}" (path "/{UU()}" (reference "{ref}") (unit 1))))')
        out.append('  )')
        # 标签落在引脚端点（角度 0 引脚端点 x-2.54；180 引脚端点 x+2.54）
        for num in nums:
            x, y = indexes[num]
            ang = 0 if x < 0 else 180
            ex = X + x + (-2.54 if x < 0 else 2.54)
            ey = Y + y
            net = p["pins"][num]
            just = "left" if ang == 0 else "right"
            out.append(f'  (global_label "{esc(net)}" (shape passive) (at {ex:.2f} {ey:.2f} 0)')
            out.append(f'    (effects (font (size 1.0 1.0)) (justify {just})) (uuid {UU()}))')
            label_count += 1
    out += ['  (sheet_instances', '    (path "/" (page "1"))', '  )', ')']
    # 后处理：name 行固定 4 个右括号（size/font/effects/name）
    fixed = []
    for line in out:
        if '(name "' in line and '(pin_names' not in line:
            line = line.rstrip(")")
            line = line + ")" * 4
        fixed.append(line)
    return "\n".join(fixed), label_count, len(refs)


def pad_for_package(pkg):
    m = re.search(r"(\d{4})", pkg or "")
    if m:
        sizes = {"0603": (0.8, 0.95), "0805": (1.0, 1.2), "1206": (1.2, 1.4), "2512": (1.6, 1.8)}
        s = sizes.get(m.group(1), (1.0, 1.2))
        return s, (s[0] + 0.6, 0.0)
    return (1.0, 1.0), (2.0, 0.0)


def gen_pcb(board_name, parts, w, h):
    nets = {}
    for ref in sorted(parts):
        for pin, net in parts[ref]["pins"].items():
            if net not in nets:
                nets[net] = len(nets) + 1
    out = ['(kicad_pcb (version 20221018) (generator pcbnew)',
           f'  (general (thickness 1.6))',
           f'  (paper "A4")',
           f'  (title_block (title "{esc(board_name)} REV.A9 preliminary") (rev "REV.A9") (comment 1 "generated; footprint dims PROVISIONAL; no DRC"))',
           '  (layers (0 "F.Cu" signal) (31 "B.Cu" signal) (32 "B.Adhes" user "B.Adhesive")',
           '    (33 "F.Adhes" user "F.Adhesive") (34 "B.Paste" user) (35 "F.Paste" user)',
           '    (36 "B.SilkS" user "B.Silkscreen") (37 "F.SilkS" user "F.Silkscreen")',
           '    (38 "B.Mask" user) (39 "F.Mask" user) (40 "Dwgs.User" user "User.Drawings")',
           '    (41 "Cmts.User" user "User.Comments") (42 "Eco1.User" user "User.Eco1")',
           '    (43 "Eco2.User" user "User.Eco2") (44 "Edge.Cuts" user) (45 "Margin" user)',
           '    (46 "B.CrtYd" user "B.Courtyard") (47 "F.CrtYd" user "F.Courtyard")',
           '    (48 "B.Fab" user) (49 "F.Fab" user))',
           '  (setup (pad_to_mask_clearance 0))',
           '  (net 0 "")']
    for net, nid in nets.items():
        out.append(f'  (net {nid} "{esc(net)}")')
    # 板框
    pts = [(0, 0), (w, 0), (w, h), (0, h), (0, 0)]
    for i in range(4):
        x1, y1 = pts[i]; x2, y2 = pts[i + 1]
        out.append(f'  (gr_line (start {x1} {y1}) (end {x2} {y2}) (layer "Edge.Cuts") (width 0.1))')
    # 安装孔
    for (mx, my) in ((4, 4), (w - 4, 4), (4, h - 4), (w - 4, h - 4)):
        out.append(f'  (footprint "MountingHole:MountingHole_3.2mm" (layer "F.Cu") (at {mx} {my})')
        out.append(f'    (property "Reference" "H{mx:.0f}{my:.0f}" (at 0 0 0) (layer "F.SilkS") (effects (font (size 1 1))))')
        out.append('    (pad "" np_thru_hole circle (at 0 0) (size 3.2 3.2) (drill 3.2) (layers "*.Cu" "*.Mask")))')
    # 器件：简化封装（矩形焊盘按引脚数排布），仅用于初布局
    i = 0
    for ref in sorted(parts):
        p = parts[ref]
        n = len(p["pins"])
        x = 8 + (i % 6) * ((w - 16) / 6)
        y = 12 + (i // 6) * (h - 24) / max(1, (len(parts) // 6 + 1))
        i += 1
        out.append(f'  (footprint "QS30:PRELIM_{n}P" (layer "F.Cu") (at {x:.2f} {y:.2f})')
        out.append(f'    (property "Reference" "{ref}" (at 0 -3 0) (layer "F.SilkS") (effects (font (size 1 1))))')
        out.append(f'    (property "Value" "{esc(p["value"][:20])}" (at 0 3 0) (layer "F.Fab") (effects (font (size 1 1)) hide))')
        cols = 2 if n > 1 else 1
        for k, (pin, net) in enumerate(sorted(p["pins"].items(), key=lambda kv: (len(kv[0]), kv[0]))):
            px = (k % cols - 0.5) * 2.5
            py = (k // cols - max(0, (n // cols) - 1) / 2) * 2.0
            out.append(f'    (pad "{esc(pin)}" smd rect (at {px:.2f} {py:.2f}) (size 1.0 1.0) (layers "F.Cu" "F.Paste" "F.Mask") (net {nets[net]} "{esc(net)}"))')
        out.append('  )')
    out.append(')')
    return "\n".join(out), len(nets), len(parts)


def netcheck(parts, sch_text):
    """从生成的原理图标签推导 nets，与 CSV 比较（只验证文件内容自洽，不是原生 ERC）。"""
    labels = re.findall(r'\(global_label "([^"]+)"', sch_text)
    from collections import Counter
    return dict(labels=len(labels), unique_nets=len(set(labels)),
                csv_nets=len({n for p in parts.values() for n in p["pins"].values()}))


def main():
    rows = load()
    boards = {
        "QS30-9_DISPLAY": dict(sheets=("MOD_L",), w=100, h=100,
                               title="QS30-9 DISPLAY module (3x QS30-1 + HV5622)"),
        "QS30-9_MAIN": dict(sheets=("MB_", "MOD_C"), w=120, h=90,
                            title="QS30-9 MAIN board (ESP32-S3 + HV PSU + center 3x QS30-1)"),
    }
    status = {"generated": [], "parsed": [], "opened_in_kicad": [], "native_erc": [],
              "native_drc": [], "netcheck": {}}
    d = os.path.join(OUT, "projects")
    os.makedirs(d, exist_ok=True)
    for name, cfg in boards.items():
        parts = parts_of(rows, cfg["sheets"])
        pdir = os.path.join(d, name)
        os.makedirs(pdir, exist_ok=True)
        sch_text, nlabels, nparts = gen_sch(name, parts, title=cfg["title"])
        # 统一修正 name 行括号数（生成器内部 f-string 易多/少一个括号）
        _ls = []
        for _l in sch_text.split("\n"):
            if _l.lstrip().startswith("(name "):
                _l = _l.rstrip(")") + ")" * 4
            _ls.append(_l)
        sch_text = "\n".join(_ls)
        pcb_text, nnets, _ = gen_pcb(name, parts, cfg["w"], cfg["h"])
        sch_path = os.path.join(pdir, f"{name}.kicad_sch")
        pcb_path = os.path.join(pdir, f"{name}.kicad_pcb")
        pro_path = os.path.join(pdir, f"{name}.kicad_pro")
        open(sch_path, "w", encoding="utf-8").write(sch_text + "\n")
        open(pcb_path, "w", encoding="utf-8").write(pcb_text + "\n")
        json.dump({"meta": {"filename": f"{name}.kicad_pro", "version": 1},
                   "board": {"design_settings": {"defaults": {"board_outline_line_width": 0.1}}},
                   "schematic": {}, "sheets": []},
                  open(pro_path, "w", encoding="utf-8"), indent=1)
        status["generated"] += [os.path.relpath(p, ROOT) for p in (pro_path, sch_path, pcb_path)]
        # L2 语法解析
        try:
            from kiutils.schematic import Schematic
            from kiutils.board import Board
            s = Schematic.from_file(sch_path, encoding="utf-8")
            b = Board.from_file(pcb_path, encoding="utf-8")
            status["parsed"] += [os.path.relpath(sch_path, ROOT),
                                 os.path.relpath(pcb_path, ROOT)]
            status["netcheck"][name] = dict(netcheck(parts, sch_text),
                                             parsed_symbols=len(s.schematicSymbols),
                                             parsed_labels=len(s.globalLabels),
                                             parsed_footprints=len(b.footprints),
                                             board_mm=[cfg["w"], cfg["h"]])
            print(f"{name}: {nparts} parts, {nlabels} labels, {nnets} nets, "
                  f"PARSE OK (symbols={len(s.schematicSymbols)}, labels={len(s.globalLabels)}, "
                  f"footprints={len(b.footprints)})")
        except Exception as e:  # noqa: BLE001
            print(f"{name}: PARSE FAIL: {e}")
            status["netcheck"][name] = dict(error=str(e))
    # 状态矩阵
    md = ["# KiCad 工程生成状态（G1）", "",
          "由 `design9/kicad_gen.py` 生成；**严格分级，不跳级**。", "",
          "| 级别 | 状态 | 证据 |", "|---|---|---|",
          f"| L1 已生成文件 | ✅ | {len(status['generated'])} 个（每板 .kicad_pro/.kicad_sch/.kicad_pcb） |",
          f"| L2 通过语法解析 | {'✅' if status['parsed'] else '❌'} | kiutils 回读成功 {len(status['parsed'])} 个文件 |",
          "| L3 能在 KiCad 打开 | ❌ 未验证 | 本环境无可用 KiCad；附件 `kicad.exe` 缺 DLL（0xC0000135） |",
          "| L4 原生 ERC | ❌ 未执行 | 需 KiCad CLI/GUI |",
          "| L5 原生 DRC | ❌ 未执行 | 需 KiCad CLI/GUI |", "",
          "## 生成内容", "",
          "| 板 | 器件数 | 标签数 | CSV 网络数 | 解析符号 | 解析标签 | 解析封装 | 板框 (mm) |",
          "|---|---|---|---|---|---|---|---|"]
    for name, nc in status["netcheck"].items():
        md.append(f"| {name} | {nc.get('csv_parts', '-')} | {nc.get('labels', '-')} | "
                  f"{nc.get('csv_nets', '-')} | {nc.get('parsed_symbols', 'FAIL')} | "
                  f"{nc.get('parsed_labels', '-')} | {nc.get('parsed_footprints', '-')} | "
                  f"{nc.get('board_mm', '-')} |")
    md += ["", "## 已知局限（必须与结论连读）", "",
           "- 原理图用「通用符号 + 引脚端点全局标签」表达连接；不是按器件库精细绘制的原理图；",
           "- PCB 为初布局（板框/安装孔/简化矩形焊盘），**未做布线、未做间距检查**；",
           "- 管座、HV 连接器、PQFP-44 等封装尺寸未核实（H9-03/H9-07），一律 PROVISIONAL；",
           "- 文件未在 KiCad 中打开过，不能声称\"可在 KiCad 打开\"；",
           "- 原生 ERC/DRC 未执行，不得以本文件替代。"]
    open(os.path.join(OUT, "GENERATED_STATUS.md"), "w", encoding="utf-8").write("\n".join(md) + "\n")
    json.dump(status, open(os.path.join(OUT, "generated_status.json"), "w",
                           encoding="utf-8"), ensure_ascii=False, indent=1)
    print("wrote kicad/GENERATED_STATUS.md + projects/")


if __name__ == "__main__":
    main()
